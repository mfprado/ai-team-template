#!/usr/bin/env python3
"""Generate each tool's files from the universal source in .agents/.

Source of truth:
  .agents/skills/          all skills (Agent Skills format)
  .agents/permissions.json what the AI may not do

Generated (never edit by hand):
  .claude/skills/          copy of .agents/skills/ (Claude Code only reads this folder)
  .claude/settings.json    permissions + hooks for Claude Code
  .codex/rules/default.rules  command rules for Codex (prefix_rule)
  .codex/hooks.json        hooks for Codex

Codex reads .agents/skills/ and AGENTS.md natively, so they are not copied.

Usage:
  python3 .agents/core/scripts/sync.py           write the generated files
  python3 .agents/core/scripts/sync.py --check   exit 1 if anything is out of date

Standard library only.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
AGENTS = ROOT / ".agents"
SKILLS_SRC = AGENTS / "skills"
POLICY = AGENTS / "permissions.json"

CLAUDE_SKILLS = ROOT / ".claude" / "skills"
CLAUDE_SETTINGS = ROOT / ".claude" / "settings.json"
CODEX_RULES = ROOT / ".codex" / "rules" / "default.rules"
CODEX_HOOKS = ROOT / ".codex" / "hooks.json"

GUARD = ".agents/core/hooks/guard.py"
SESSION_START = ".agents/core/hooks/session_start.py"


def load_policy():
    with POLICY.open(encoding="utf-8") as f:
        return json.load(f).get("rules", [])


def strip_globstar(pattern):
    """'**/.env' -> '.env' (Claude Code treats a bare name as 'at any depth')."""
    while pattern.startswith("**/"):
        pattern = pattern[3:]
    return pattern


# ---------- Claude Code ----------

def claude_permissions(rules):
    perms = {"allow": [], "ask": [], "deny": []}
    for rule in rules:
        tier = rule.get("tier", "deny")
        tool = rule.get("tool", "")
        pattern = rule.get("pattern")
        if tier not in perms:
            continue
        if tool == "Bash" and pattern:
            perms[tier] += [f"Bash({pattern})", f"Bash({pattern} *)"]
        elif tool == "Read" and pattern:
            perms[tier].append(f"Read({strip_globstar(pattern)})")
        elif "*" not in tool and pattern is None:
            perms[tier].append(tool)
        # Tool-name globs in the middle of a name (e.g. mcp__*send*) cannot be
        # expressed in Claude Code settings: the guard hook enforces them.
    return {k: v for k, v in perms.items() if v}


def claude_settings(rules):
    guard = f'python3 "$CLAUDE_PROJECT_DIR/{GUARD}"'
    start = f'python3 "$CLAUDE_PROJECT_DIR/{SESSION_START}"'
    settings = {
        "permissions": claude_permissions(rules),
        "hooks": {
            "PreToolUse": [{"matcher": "*", "hooks": [{"type": "command", "command": guard}]}],
            "SessionStart": [{"hooks": [{"type": "command", "command": start}]}],
        },
    }
    return json.dumps(settings, indent=2, ensure_ascii=False) + "\n"


# ---------- Codex ----------

def codex_rules(rules):
    decision = {"deny": "forbidden", "ask": "prompt", "allow": "allow"}
    lines = [
        "# Generated by .agents/core/scripts/sync.py from .agents/permissions.json.",
        "# Do not edit: change .agents/permissions.json and run sync.py.",
        "",
    ]
    for rule in rules:
        if rule.get("tool") != "Bash" or not rule.get("pattern"):
            continue
        tokens = json.dumps(rule["pattern"].split(), ensure_ascii=False)
        reason = json.dumps(rule.get("reason", ""), ensure_ascii=False)
        lines += [
            "prefix_rule(",
            f"    pattern = {tokens},",
            f'    decision = "{decision.get(rule.get("tier", "deny"), "forbidden")}",',
            f"    justification = {reason},",
            ")",
            "",
        ]
    return "\n".join(lines)


def codex_hooks():
    top = '"$(git rev-parse --show-toplevel)"'
    hooks = {
        "hooks": {
            "PreToolUse": [{"matcher": "*", "hooks": [{"type": "command", "command": f"python3 {top}/{GUARD}"}]}],
            "SessionStart": [{"hooks": [{"type": "command", "command": f"python3 {top}/{SESSION_START}"}]}],
        }
    }
    return json.dumps(hooks, indent=2) + "\n"


# ---------- Build and compare ----------

def desired_files():
    rules = load_policy()
    files = {
        CLAUDE_SETTINGS: claude_settings(rules).encode(),
        CODEX_RULES: codex_rules(rules).encode(),
        CODEX_HOOKS: codex_hooks().encode(),
    }
    if SKILLS_SRC.is_dir():
        for src in sorted(SKILLS_SRC.rglob("*")):
            if src.is_file() and "__pycache__" not in src.parts:
                files[CLAUDE_SKILLS / src.relative_to(SKILLS_SRC)] = src.read_bytes()
    return files


def stale_skill_files(files):
    if not CLAUDE_SKILLS.is_dir():
        return []
    return [p for p in CLAUDE_SKILLS.rglob("*") if p.is_file() and p not in files]


def main():
    check = "--check" in sys.argv[1:]
    files = desired_files()
    changed = [p for p, data in files.items() if not p.is_file() or p.read_bytes() != data]
    stale = stale_skill_files(files)

    if check:
        if changed or stale:
            for p in changed + stale:
                print(f"out of date: {p.relative_to(ROOT)}")
            print("Run: python3 .agents/core/scripts/sync.py")
            return 1
        return 0

    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(files[p])
        if CLAUDE_SKILLS in p.parents:  # keep scripts executable
            p.chmod((SKILLS_SRC / p.relative_to(CLAUDE_SKILLS)).stat().st_mode)
    for p in stale:
        p.unlink()
    if CLAUDE_SKILLS.is_dir():
        for d in sorted((d for d in CLAUDE_SKILLS.rglob("*") if d.is_dir()), reverse=True):
            if not any(d.iterdir()):
                d.rmdir()
    if changed or stale:
        print(f"sync: {len(changed)} written, {len(stale)} removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
